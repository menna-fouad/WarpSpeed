`default_nettype none
`timescale 1ns/1ps
module memory_coalescing_unit (
    input logic clk,
    input logic reset,
    // input from ALU
    input logic [7:0][31:0] addr,
    input logic [7:0][31:0] src2, // store data
    input logic [7:0] valid,
    input logic is_load,
    input logic is_store,
    input logic sub_warp_valid,
    input logic [1:0] sub_warp_cycle,
    input logic [9:0] reg_bank_addr,

    // interface to data cache
    output logic req_valid,
    input logic req_ready,
    output logic [31:0] req_addr,
    output logic req_write,
    output logic [1023:0] wr_data,
    output logic [31:0] wr_word_en,

    // load store unit interface
    input logic lsu_ready,
    output logic txn_valid,
    output logic txn_is_load,
    output logic txn_last,
    output logic [2:0] txn_warp,
    output logic [4:0] txn_dst,
    output logic [31:0] txn_match_mask,
    output logic [31:0][4:0] txn_word_sel // select requested word from cache line
);
    typedef enum logic [1:0] {
        EMPTY,
        ACCUM,
        READY,
        ISSUING
    } slot_state_t;

    typedef enum logic [2:0] {
        IDLE,
        COPY,
        SELECT_LINE,
        PREPARE_GROUP,
        BUILD,
        ISSUE
    } issue_state_t;

    // Per-warp instruction storage
    //    [warp][thread][data]
    logic [7:0][31:0][31:0] slot_addr; // Memory address generated by each thread
    logic [7:0][31:0][31:0] slot_store_data; // Store value from each thread

    //    [warp][thread]
    logic [7:0][31:0] slot_mask; // Active threads for this instruction

    // Instruction metadata
    logic [7:0] slot_is_store; // no need for slot_is_load since its simply ~slot_is_store
    logic [7:0][4:0] slot_dst; // destination register

    // Current state of each warp's slot
    slot_state_t slot_state [7:0]; // current state for each warp
    issue_state_t issue_state;

    logic [7:0][2:0] ready_fifo;
    logic [3:0] ready_count;

    logic [2:0] incoming_warp;
    logic [4:0] incoming_dst;

    assign incoming_warp = reg_bank_addr[9:7];
    assign incoming_dst  = reg_bank_addr[4:0];

    always_ff @(posedge clk) begin
        if (sub_warp_valid && (is_load || is_store)) begin
            slot_addr[incoming_warp][sub_warp_cycle*8 +: 8] <= addr;
            slot_store_data[incoming_warp][sub_warp_cycle*8 +: 8] <= src2;
            slot_mask[incoming_warp][sub_warp_cycle*8 +: 8] <= valid;
            slot_is_store[incoming_warp] <= is_store;
            slot_dst[incoming_warp] <= incoming_dst;
        end
    end

    logic fifo_push, fifo_pop;
    (* max_fanout = 32 *) logic [2:0] issuing_warp;
    logic issue_done;
    logic direct_handoff;

    assign issue_done = req_valid && req_ready && txn_last;

    assign fifo_push = sub_warp_valid && (is_load || is_store) && (&sub_warp_cycle);
    assign fifo_pop = |ready_count && issue_done;

    assign direct_handoff = (ready_count == 0) && fifo_push && (issue_done || (issue_state == IDLE));

    always_ff @(posedge clk) begin
        if (reset)
            ready_count <= 4'd0;
        else begin
            case ({fifo_push && !direct_handoff, fifo_pop})
                2'b10 : begin // push only
                    ready_fifo[ready_count] <= incoming_warp;
                    ready_count <= ready_count + 4'd1;
                end

                2'b01 : begin // pop only
                    for (int i = 0; i < 7; ++i) begin
                        ready_fifo[i] <= ready_fifo[i + 1];
                    end
                    ready_count <= ready_count - 4'd1;
                end

                2'b11 : begin // push and pop
                    for (int i = 0; i < 7; ++i)
                        ready_fifo[i] <= ready_fifo[i + 1];
                    
                    ready_fifo[ready_count - 1] <= incoming_warp;
                    // ready_count doesn't change since one left and one entered
                end

                default : ; // do nothing
            endcase
        end
    end

    always_ff @(posedge clk) begin
        if (reset) begin
            issuing_warp <= 3'b0;

            for (int w = 0; w < 8; ++w)
                slot_state[w] <= EMPTY;
        end else begin
            if (sub_warp_valid && (is_load || is_store))
                slot_state[incoming_warp] <= (&sub_warp_cycle) ? READY : ACCUM;

            if (fifo_pop) begin
                issuing_warp <= ready_fifo[0];
                slot_state[ready_fifo[0]] <= ISSUING;
            end else if (direct_handoff) begin
                issuing_warp <= incoming_warp;
                slot_state[incoming_warp] <= ISSUING;
            end

            if (req_valid && req_ready && txn_last)
                slot_state[issuing_warp] <= EMPTY;
        end
    end

    logic [31:0][31:0] curr_addr;
    logic [31:0][31:0] curr_store_data;
    logic [31:0] curr_mask;
    logic [31:0] curr_claimed; // threads already included in accepted cache transactions
    logic curr_is_store;
    logic [4:0] curr_dst;

    logic [31:0] remaining, remaining_q;

    logic [4:0] selected_thread;
    logic selected_thread_valid, selected_thread_valid_q;

    logic [24:0] selected_line;
    logic [31:0] group_mask;

    // Next group, registered in PREPARE_GROUP; BUILD, ISSUE and the outputs only use these
    logic [31:0] group_mask_q;
    logic [24:0] selected_line_q;
    logic txn_last_q, group_valid_q;

    logic [1:0] build_idx;
    logic [31:0] wr_word_en_q;
    logic [1023:0] wr_data_q;

    issue_state_t issue_state_next;

    // Next-state logic
    always_comb begin
        issue_state_next = issue_state;
        case (issue_state)
            COPY          : issue_state_next = SELECT_LINE;
            SELECT_LINE   : issue_state_next = PREPARE_GROUP;
            PREPARE_GROUP : issue_state_next = curr_is_store ? BUILD : ISSUE;
            BUILD         : if (build_idx == 2'd3) issue_state_next = ISSUE;
            ISSUE         : if (txn_valid) issue_state_next = txn_last ? IDLE : SELECT_LINE;
            default       : ;
        endcase
    end

    // State register
    always_ff @(posedge clk) begin
        if (reset)
            issue_state <= IDLE;
        else if (fifo_pop || direct_handoff)
            issue_state <= COPY;
        else
            issue_state <= issue_state_next;
    end

    always_ff @(posedge clk) begin
        case (issue_state)
            COPY : begin
                curr_addr <= slot_addr[issuing_warp];
                curr_store_data <= slot_store_data[issuing_warp];
                curr_mask <= slot_mask[issuing_warp];
                curr_claimed <= '0;
                curr_is_store <= slot_is_store[issuing_warp];
                curr_dst <= slot_dst[issuing_warp];
            end

            SELECT_LINE : begin
                selected_thread_valid_q <= selected_thread_valid;
                selected_line_q <= selected_line;
                remaining_q <= remaining;
            end

            PREPARE_GROUP : begin
                group_mask_q <= group_mask;
                group_valid_q <= selected_thread_valid_q;
                txn_last_q <= selected_thread_valid_q && (remaining_q == group_mask);

                build_idx <= 0;
                wr_word_en_q <= '0;
            end

            BUILD : begin
                for (int i = 0; i < 8; ++i) begin
                    if (group_mask_q[{build_idx, i[2:0]}]) begin
                        wr_data_q[curr_addr[{build_idx, i[2:0]}][6:2]*32 +: 32] <= curr_store_data[{build_idx, i[2:0]}];
                        wr_word_en_q[curr_addr[{build_idx, i[2:0]}][6:2]] <= 1'b1;
                    end
                end
                build_idx <= build_idx + 1;
            end

            ISSUE : if (txn_valid)
                curr_claimed <= curr_claimed | group_mask_q;

            default : ;
        endcase
    end

    always_comb begin
        remaining = curr_mask & ~curr_claimed;

        selected_thread = 5'd0;
        selected_thread_valid = |remaining;

        for (int t = 31; t >= 0; --t) begin
            if (remaining[t]) begin
                selected_thread = t[4:0];
            end
        end

        selected_line = curr_addr[selected_thread][31:7];

        for (int t = 0; t < 32; ++t)
            group_mask[t] = remaining_q[t] && (curr_addr[t][31:7] == selected_line_q);

        req_valid = (issue_state == ISSUE) && group_valid_q && lsu_ready;
        req_addr = {selected_line_q, 7'b0};
        req_write = curr_is_store;
        wr_data = wr_data_q;
        wr_word_en = wr_word_en_q;

        txn_valid = req_valid && req_ready;
        txn_is_load = !curr_is_store;
        txn_warp = issuing_warp;
        txn_dst = curr_dst;
        txn_match_mask = group_mask_q;
        txn_last = txn_last_q;

        for (int t = 0; t < 32; ++t) begin
            txn_word_sel[t] = curr_addr[t][6:2];
        end
    end

    // Simulation assertions
    `ifndef SYNTHESIS
        // A new memory instruction must not overwrite an occupied slot
        always_ff @(posedge clk) begin
            if (!reset && sub_warp_valid && (is_load || is_store) && ~|sub_warp_cycle) begin
                assert (slot_state[incoming_warp] == EMPTY)
                    else $error("Coalescer: warp %0d started a new memory instruction while slot state = %0d",
                                incoming_warp, slot_state[incoming_warp]);
            end
        end

        // Subwarps 1-3 should belong to an instruction currently being accumulated
        always_ff @(posedge clk) begin
            if (!reset && sub_warp_valid && (is_load || is_store) && |sub_warp_cycle) begin
                assert (slot_state[incoming_warp] == ACCUM)
                    else $error("Coalescer: warp %0d received subwarp %0d while slot state = %0d",
                                incoming_warp, sub_warp_cycle, slot_state[incoming_warp]);
            end
        end

        // Ready FIFO can never contain more than 8 warps
        always_ff @(posedge clk) begin
            if (!reset) begin
                assert (ready_count <= 8)
                    else $error("Coalescer: ready FIFO overflow, ready_count = %0d", ready_count);
            end
        end
    `endif
endmodule
